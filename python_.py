import pandas as pd

import sqlite3

import matplotlib.pyplot as plt
import seaborn as sns

conexao = sqlite3.connect('dados_vendas.db')

cursor = conexao.cursor()

#Criando tabela vendas1
cursor.execute("""
CREATE TABLE IF NOT EXISTS vendas1 (
    id_venda INTEGER PRIMARY KEY AUTOINCREMENT,
    data_venda DATE,
    produto TEXT,
    categoria TEXT,
    valor_venda REAL
)
""")

#Imputando dados na tabela vendas1
cursor.execute("""
INSERT INTO vendas1 (data_venda, produto, categoria, valor_venda)
VALUES
    ('2023-01-01', 'Produto A', 'Eletrônicos', 1500.00),
    ('2023-01-05', 'Produto B', 'Roupas', 350.00),
    ('2023-02-10', 'Produto C', 'Eletrônicos', 1200.00),
    ('2023-03-15', 'Produto D', 'Livros', 200.00),
    ('2023-03-20', 'Produto E', 'Eletrônicos', 800.00),
    ('2023-04-02', 'Produto F', 'Roupas', 400.00),
    ('2023-05-05', 'Produto G', 'Livros', 150.00),
    ('2023-06-10', 'Produto H', 'Eletrônicos', 1000.00),
    ('2023-07-20', 'Produto I', 'Roupas', 600.00),
    ('2023-08-25', 'Produto J', 'Eletrônicos', 700.00),
    ('2023-09-30', 'Produto K', 'Livros', 300.00),
    ('2023-10-05', 'Produto L', 'Roupas', 450.00),
    ('2023-11-15', 'Produto M', 'Eletrônicos', 900.00),
    ('2023-12-20', 'Produto N', 'Livros', 250.00)
""")
conexao.commit()

#consultando dados da tabela (categoria)
cursor.execute("""
SELECT * FROM vendas1 WHERE categoria = 'Eletrônicos'
""")

dados = cursor.fetchall()

for linha in dados:
    print(linha)

#consultando todos dados da tabela
cursor.execute("""
SELECT * FROM vendas1
""")

dados = cursor.fetchall()

for linha in dados:
    print(linha)

df = pd.read_sql_query(
"SELECT * FROM vendas1",
conexao
)

print(df.head())

#teste para validar conexao com o data base
print(df)

#Categoria que mais gera receita
sns.barplot(
    data=df,
    x='categoria',
    y='valor_venda',
    estimator=sum
)
plt.show()

#Filtro de números de vendas realizadas por categoria
sns.countplot(
data=df,
x='categoria'
)
plt.show()

#Valor medio de vendas
sns.boxplot(
    data=df,
    y='valor_venda'
)
plt.show()

